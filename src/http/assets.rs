use axum::{
    body::{Body, Bytes},
    http::{HeaderMap, HeaderValue, Method, StatusCode, Uri, header},
    response::{IntoResponse, Response},
};
use flate2::{Compression, write::GzEncoder};
use rust_embed::{EmbeddedFile, RustEmbed};
use sha2::{Digest, Sha256};

#[derive(RustEmbed)]
#[folder = "frontend/"]
#[include = "index.html"]
#[include = "src/**"]
#[include = "views/**"]
#[include = "styles/**"]
#[include = "icons/**"]
#[include = "vendor/**"]
#[exclude = "**/.DS_Store"]
#[exclude = "**/README*"]
#[exclude = "**/*.md"]
#[exclude = "**/*.json"]
