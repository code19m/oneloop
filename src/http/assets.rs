#[exclude = "vendor/cdn-assets/*.css"]
struct FrontendAssets;

/// The folders whose files the client loads by URL; `index.html` points into
/// them through `/v/<version>/`. build.rs watches the same folders.
const ASSET_DIRS: [&str; 5] = ["src", "views", "styles", "icons", "vendor"];

/// Names the embedded file set: a hash of each file's path and content hash.
/// It changes with any served file, so browsers may keep `/v/<version>/`
/// files for good. A debug build reads the files from disk and computes it
/// once per process.
fn asset_version() -> &'static str {
    static VERSION: LazyLock<String> = LazyLock::new(|| {
        let mut names = FrontendAssets::iter().collect::<Vec<_>>();
        names.sort();
        let mut hash = Sha256::new();
        for name in names {
            if let Some(file) = FrontendAssets::get(&name) {
                hash.update((name.len() as u64).to_le_bytes());
                hash.update(name.as_bytes());
                hash.update(file.metadata.sha256_hash());
            }
        }
        hex::encode(hash.finalize())
    });
    &VERSION
}

/// License texts of the bundled third-party components, generated by
/// `scripts/third-party-notices.mjs`.
const THIRD_PARTY_NOTICES: &[u8] = include_bytes!("../../THIRD_PARTY_NOTICES.md");

pub(crate) async fn serve(method: Method, uri: Uri, headers: HeaderMap) -> Response {
    if method != Method::GET && method != Method::HEAD {
        return (
            StatusCode::METHOD_NOT_ALLOWED,
            [(header::ALLOW, "GET, HEAD")],
        )
            .into_response();
    }
    if uri.path() == "/THIRD_PARTY_NOTICES.md" {
        return notices_response(method == Method::HEAD);
    }
    let mut path = uri.path();
    let mut versioned = false;
    if let Some(rest) = path.strip_prefix("/v/") {
        let Some((version, asset)) = rest.split_once('/') else {
            return StatusCode::NOT_FOUND.into_response();
        };
        if version != asset_version()
            || !asset
                .split_once('/')
                .is_some_and(|(directory, _)| ASSET_DIRS.contains(&directory))
        {
            return StatusCode::NOT_FOUND.into_response();
        }
        path = &path[(3 + version.len())..];
        versioned = true;
    }
    if path.starts_with("/api/")
        || path == "/api"
        || path.starts_with("/mcp")
        || path.starts_with("/.well-known/")
    {
        return crate::AppError::NotFound {
            resource: "endpoint",
        }
        .into_response();
    }
    if path.contains('\\') || path.split('/').any(|part| part == ".." || part == ".") {
        return StatusCode::NOT_FOUND.into_response();
    }
    let key = path.trim_start_matches('/');
    let asset = FrontendAssets::get(key)
        .map(|file| (file, key))
        .or_else(|| {
            let html_navigation = headers
                .get(header::ACCEPT)
                .and_then(|value| value.to_str().ok())
                .is_some_and(|value| value.contains("text/html"));
            (!versioned
                && (path == "/"
                    || (html_navigation
                        && !key.rsplit('/').next().unwrap_or_default().contains('.'))))
            .then(|| FrontendAssets::get("index.html").map(|file| (file, "index.html")))
            .flatten()
        });
    match asset {
        Some((file, key)) => {
            asset_response(file, key, method == Method::HEAD, &headers, versioned).await
        }
        None => StatusCode::NOT_FOUND.into_response(),
    }
}

/// Serves the notices as plain text so browsers show them without rendering.
fn notices_response(head: bool) -> Response {
    let body = if head {
        Body::empty()
    } else {
        Body::from(THIRD_PARTY_NOTICES)
    };
    let mut response = Response::new(body);
    let headers = response.headers_mut();
    headers.insert(
        header::CONTENT_TYPE,
        HeaderValue::from_static("text/plain; charset=utf-8"),
    );
    headers.insert(
        header::CONTENT_LENGTH,
        HeaderValue::from(THIRD_PARTY_NOTICES.len()),
    );
    headers.insert(header::CACHE_CONTROL, HeaderValue::from_static("no-cache"));
    headers.insert(
        header::X_CONTENT_TYPE_OPTIONS,
        HeaderValue::from_static("nosniff"),
    );
    response
}

async fn asset_response(
    mut file: EmbeddedFile,
    key: &str,
    head: bool,
    request: &HeaderMap,
    versioned: bool,
) -> Response {
    let digest: [u8; 32] = if key == "index.html" {
        let prefix = format!("/v/{}", asset_version());
        let mut html = String::from_utf8_lossy(&file.data).into_owned();
        for directory in ASSET_DIRS {
            html = html.replace(
                &format!("\"/{directory}/"),
                &format!("\"{prefix}/{directory}/"),
            );
        }
        let digest = Sha256::digest(html.as_bytes()).into();
        file.data = Cow::Owned(html.into_bytes());
        digest
    } else {
        file.metadata.sha256_hash()
    };
    let etag = format!("\"{}\"", hex::encode(digest));
    let unchanged = request
        .get(header::IF_NONE_MATCH)
        .and_then(|value| value.to_str().ok())
        .is_some_and(|value| {
            value.split(',').any(|tag| {
                let tag = tag.trim();
                tag == "*" || tag.strip_prefix("W/").unwrap_or(tag) == etag
            })
        });
    let mime = if key.ends_with(".js") || key.ends_with(".mjs") {
        "text/javascript; charset=utf-8".to_owned()
    } else {
        mime_guess::from_path(key)
            .first_or_octet_stream()
            .to_string()
    };
    // Fonts and images are compressed already.
    let gzip = if file.data.len() > 1024
        && (mime.starts_with("text/") || mime == "image/svg+xml")
        && accepts_gzip(request)
    {
        gzip_body(digest, &file.data).await
    } else {
        None
    };
    let encoded = gzip.is_some();
    let length = gzip.as_ref().map_or(file.data.len(), Bytes::len);
    let body = if head || unchanged {
        Body::empty()
    } else if let Some(bytes) = gzip {
        Body::from(bytes)
    } else {
        match file.data {
            Cow::Borrowed(bytes) => Body::from(bytes),
            Cow::Owned(bytes) => Body::from(bytes),
        }
    };
    let mut response = Response::new(body);
    if unchanged {
        *response.status_mut() = StatusCode::NOT_MODIFIED;
    }
    let headers = response.headers_mut();
    if let Ok(value) = HeaderValue::from_str(&mime) {
        headers.insert(header::CONTENT_TYPE, value);
    }
    // The gzip body is another representation, so its tag is weak.
    let etag = if encoded { format!("W/{etag}") } else { etag };
    if let Ok(value) = HeaderValue::from_str(&etag) {
        headers.insert(header::ETAG, value);
    }
    if encoded {
        headers.insert(header::CONTENT_ENCODING, HeaderValue::from_static("gzip"));
    }
    if !unchanged && let Ok(value) = HeaderValue::from_str(&length.to_string()) {
        headers.insert(header::CONTENT_LENGTH, value);
    }
    headers.insert(
        header::CACHE_CONTROL,
        HeaderValue::from_static(if versioned {
            "public, max-age=31536000, immutable"
        } else {
            "no-cache"
        }),
    );
    headers.insert(header::VARY, HeaderValue::from_static("Accept-Encoding"));
    headers.insert(
        header::X_CONTENT_TYPE_OPTIONS,
        HeaderValue::from_static("nosniff"),
    );
    if key == "views/diagram-renderer.html" {
        headers.insert(
            header::CONTENT_SECURITY_POLICY,
            super::security::diagram_renderer_policy(),
        );
        headers.insert(
            header::X_FRAME_OPTIONS,
            HeaderValue::from_static("SAMEORIGIN"),
        );
    }
    response
}

/// Whether the request lists `gzip` in `Accept-Encoding` without `q=0`.
fn accepts_gzip(request: &HeaderMap) -> bool {
    request
        .get_all(header::ACCEPT_ENCODING)
        .iter()
        .filter_map(|value| value.to_str().ok())
        .flat_map(|value| value.split(','))
        .any(|coding| {
            let mut parts = coding.split(';').map(str::trim);
            parts
                .next()
                .is_some_and(|name| name.eq_ignore_ascii_case("gzip"))
                && !parts.any(|part| {
                    part.strip_prefix("q=")
                        .is_some_and(|q| q.parse::<f32>().is_ok_and(|q| q == 0.0))
                })
        })
}

/// The gzip body of `data`, made once per SHA-256 `digest`. Bytes never change
/// under their digest, so a kept body never goes stale.
async fn gzip_body(digest: [u8; 32], data: &[u8]) -> Option<Bytes> {
    static BODIES: LazyLock<Mutex<HashMap<[u8; 32], Bytes>>> = LazyLock::new(Default::default);
    if let Some(body) = BODIES.lock().expect("gzip bodies lock").get(&digest) {
        return Some(body.clone());
    }
    let data = data.to_vec();
    let compressed = tokio::task::spawn_blocking(move || {
        let mut encoder = GzEncoder::new(Vec::new(), Compression::default());
        encoder.write_all(&data)?;
        encoder.finish()
    })
    .await;
    let body = Bytes::from(compressed.ok()?.ok()?);
    BODIES
        .lock()
        .expect("gzip bodies lock")
        .insert(digest, body.clone());
    Some(body)
}
